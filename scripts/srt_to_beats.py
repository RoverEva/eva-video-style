#!/usr/bin/env python3
"""Turn a talking-head SRT into a beat plan for the native 9:16 industry templates (template/industry/*).

The spoken lines are never rewritten: every on-screen word is copied from the SRT. The script only decides
  role  hero (first line) | item (middle lines, shown as an icon list that builds up) | close (last line)
  hl    the highlighted (red) phrase inside a hero/close line, from a keyword list
  icon  an icon name for each item, from keywords (default: check)
  split where a hero/close line breaks into two lines (just before the highlight when there is one)

usage: srt_to_beats.py talk.srt out/data.js [--end SECONDS] [--keys 心动,自住,...] [--var RE]
"""
import re, sys, json

def parse_srt(path):
    txt = open(path, encoding='utf-8-sig').read().replace('\r', '')
    out = []
    for blk in re.split(r'\n\s*\n', txt.strip()):
        ls = [l for l in blk.split('\n') if l.strip()]
        tl = next((i for i, l in enumerate(ls) if '-->' in l), None)
        if tl is None: continue
        a, b = [s.strip() for s in ls[tl].split('-->')]
        sec = lambda s: (lambda h, m, x: int(h) * 3600 + int(m) * 60 + float(x.replace(',', '.')))(*s.split(':'))
        out.append({'t0': round(sec(a), 3), 't1': round(sec(b), 3), 'text': ''.join(ls[tl + 1:]).strip()})
    return out

KEYS = ['心动', '自住', '豪宅', '松弛感', '采光', '空间', '庭院', '花园', '学区', '地段', '性价比', '保值', '景观', '泳池', '厨房', '主卧']
ICONS = [('采光|阳光|落地窗|光', 'sun'), ('空间|宽敞|大', 'space'), ('庭院|花园|院|绿', 'tree'), ('厨房', 'kitchen'), ('卧|房间', 'bed'),
         ('卫|浴', 'bath'), ('位置|地段|通勤|交通', 'pin'), ('学区|学校', 'school'), ('泳池', 'pool'), ('外立面|现代|设计', 'house')]

def highlight(text, keys):
    for k in keys:
        i = text.find(k)
        if i < 0: continue
        a, b = i, i + len(k)
        if a > 0 and text[a - 1] in '超太很好最': a -= 1          # 超心动 · 太适合
        if b < len(text) and text[b] in '了啊呀吧': b += 1         # 自住了
        return text[a:b]
    return ''

def split_line(text, hl):
    if hl and text.find(hl) > 1: i = text.find(hl)
    else: i = (len(text) + 1) // 2
    return [text[:i], text[i:]]

def main():
    a = sys.argv[1:]
    if len(a) < 2: sys.exit(__doc__)
    opt = lambda k, d=None: a[a.index(k) + 1] if k in a else d
    cues = parse_srt(a[0]); keys = opt('--keys').split(',') if opt('--keys') else KEYS
    end = float(opt('--end', cues[-1]['t1'] + .1))
    beats = []
    for i, c in enumerate(cues):
        role = 'hero' if i == 0 else 'close' if i == len(cues) - 1 and len(cues) > 1 else 'item'
        b = dict(c, role=role)
        if role == 'item':
            b['icon'] = next((ic for pat, ic in ICONS if re.search(pat, c['text'])), 'check')
        else:
            b['hl'] = highlight(c['text'], keys); b['lines'] = split_line(c['text'], b['hl'])
        beats.append(b)
    js = f"/* generated by scripts/srt_to_beats.py from {a[0].split('/')[-1]} — on-screen text is the SRT, unchanged */\nwindow.{opt('--var', 'RE')} = " + json.dumps({'end': end, 'beats': beats}, ensure_ascii=False, indent=1) + ';\n'
    open(a[1], 'w', encoding='utf-8').write(js); print(a[1], len(beats), 'beats')

if __name__ == '__main__': main()
